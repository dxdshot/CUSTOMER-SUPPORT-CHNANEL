const v = (id: string, body: string, at: string, day: "Today" | "Yesterday" = "Today"): Message => ({
  id,
  author: "visitor",
  body,
  at,
  day,
});

const a = (id: string, body: string, at: string, day: "Today" | "Yesterday" = "Today"): Message => ({
  id,
  author: "agent",
  name: "You",
  body,
  at,
  day,
  read: true,
});

const s = (id: string, body: string, at: string, day: "Today" | "Yesterday" = "Today"): Message => ({
  id,
  author: "system",
  body,
  at,
  day,
});

type ConversationInput = {
  id: string;
  visitor: Visitor;
  status: ConversationStatus;
  assignee?: string | null;
  tags: string[];
  unread: number;
  updatedMinutes: number;
  updatedLabel?: string;
  typing?: boolean;
  csat?: "good" | "bad";
  messages: Message[];
};

function conversation(input: ConversationInput): Conversation {
  // A system note ("conversation closed") should not become the inbox preview.
  const last = [...input.messages].reverse().find((message) => message.author !== "system");
  return {
    ...input,
    assignee: input.assignee ?? null,
    updatedLabel: input.updatedLabel ?? `${input.updatedMinutes}m`,
    lastMessage: last?.body ?? "",
    historyLoaded: true,
  };
}

